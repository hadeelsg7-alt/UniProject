"""Arabic (MSA + Saudi dialect) cue lexicons used by the agent tools and by the
offline rule-based reasoner. All cues are normalised once at import time, so
they can be written naturally here (with ة / ى / أ ...).

These lexicons are transparent and editable; they are NOT a trained model.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from arabic_text import normalize


def _n(words: list[str]) -> list[str]:
    seen, out = set(), []
    for w in words:
        nw = normalize(w)
        if nw and nw not in seen:
            seen.add(nw)
            out.append(nw)
    return out


@dataclass
class Topic:
    key: str
    label_en: str
    cues: list[str]
    problem_dimension: str
    suggestion_dimension: str
    specificity: int  # higher = more specific / higher risk, wins when merged
    inherent_problem: bool = False  # the cue itself describes a problem (e.g. "freezes")
    gateway: bool = False  # login/payment/registration: a problem here blocks the journey
    risk_flag: str | None = None
    extra: dict = field(default_factory=dict)


